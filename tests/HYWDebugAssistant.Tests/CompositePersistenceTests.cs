    [Fact]
    public void 加载_旧版单源网络应归一为多源字段并升版写回()
    {
        // 【R3 格式迁移】v1 的 `source`（单源字符串）读出即归一为 `sources`（数组）；
        // 写回**升版到 v2 并清掉旧字段**——绝不让两个字段同时存在于文件里（那是第二事实源）。
        using var harness = new Harness(("gen", typeof(GeneratorModule)), ("sink", typeof(SinkModule)));
        var path = harness.PathFor("legacy-v1.json");

        File.WriteAllText(path, """
        {
          "schemaVersion": 1,
          "instances": [
            { "instanceId": "g1", "moduleId": "test/gen/1.0.0", "enabled": true },
            { "instanceId": "s1", "moduleId": "test/sink/1.0.0", "enabled": true }
          ],
          "networks": [
            { "name": "link-1", "isAutoGenerated": false, "source": "g1.out", "targets": ["s1.in"] }
          ]
        }
        """);

        harness.Services.LoadComposite(path).Succeeded.ShouldBeTrue();

        var network = harness.Services.GetNetworks().Single();
        network.Sources.ShouldBe(["g1.out"], "旧版单源字段读出即归一为**源集合**");
        network.Targets.ShouldBe(SinkInMember);

        var resaved = harness.PathFor("legacy-v1-resaved.json");
        harness.Services.SaveComposite(resaved, "legacy").Succeeded.ShouldBeTrue();

        var root = JsonNode.Parse(File.ReadAllText(resaved))!.AsObject();
        root["schemaVersion"]!.GetValue<int>().ShouldBe(3, "写回即升版到当前版本（v3 = 布局改用 DIP）");

        var entry = root["networks"]!.AsArray()[0]!.AsObject();
        entry["sources"]!.AsArray().Select(n => n!.GetValue<string>()).ShouldBe(["g1.out"]);
        entry.ShouldNotContainKey("source", "旧字段必须被清掉：两个字段并存 = 第二事实源");
    }

    [Fact]
    public void 加载_旧版布局应按屏幕缩放归一为DIP并升版写回()
    {
        // v2 及更早的 `layout.*` 四数是**屏幕物理像素**，v3 起一律 DIP（见 `ModuleLayoutView`）。
        // 单位归一的**唯一一处**在解析期：按屏幕缩放 ÷。这条用例把它钉住 ——
        // 不归一的话，150% 的屏上这样的组合件会以 1.5 倍的尺寸开窗（右边框长出屏幕）。
        using var harness = new Harness(("gen", typeof(GeneratorModule)));
        var path = harness.PathFor("legacy-v2-layout.json");

        File.WriteAllText(path, """
        {
          "schemaVersion": 2,
          "instances": [
            { "instanceId": "g1", "moduleId": "test/gen/1.0.0", "enabled": true }
          ],
          "networks": [],
          "layout": {
            "g1": { "x": 100, "y": 200, "width": 400, "height": 300, "viewVisible": true }
          }
        }
        """);

        CompositeService.ScreenScale = 2.0;
        try
        {
            harness.Services.LoadComposite(path).Succeeded.ShouldBeTrue();
        }
        finally
        {
            CompositeService.ScreenScale = 1.0;
        }

        harness.Runtime.Content.Layout.TryGetModule("g1", out var loaded).ShouldBeTrue();
        loaded!.X.ShouldBe(50, "X 按缩放归一为 DIP");
        loaded.Y.ShouldBe(100, "Y 按缩放归一为 DIP");
        loaded.Width.ShouldBe(200, "Width 按缩放归一为 DIP");
        loaded.Height.ShouldBe(150, "Height 按缩放归一为 DIP");

        // 写回：升版到 v3，且写出的是**已归一**的 DIP 值（不再二次换算）
        var resaved = harness.PathFor("legacy-v2-layout-resaved.json");
        harness.Services.SaveComposite(resaved, "legacy").Succeeded.ShouldBeTrue();

        var root = JsonNode.Parse(File.ReadAllText(resaved))!.AsObject();
        root["schemaVersion"]!.GetValue<int>().ShouldBe(3);

        var saved = root["layout"]!["g1"]!.AsObject();
        saved["width"]!.GetValue<double>().ShouldBe(200, "v3 里写的是 DIP");
        saved["height"]!.GetValue<double>().ShouldBe(150);
    }

    [Fact]
    public void 加载_多源网络_部分源未锚定应不停流且逐源报Issue()
    {
        // **部分源不可用 ≠ 停流**：其余源照常投递，只对该源报 Issue；
        // 未锚定的源**保留声明**（进 UnresolvedSources），补齐模块后自动重锚。
        using var harness = new Harness(("sink", typeof(SinkModule)));
        var path = harness.PathFor("multi-partial.json");

        File.WriteAllText(path, """
        {
          "schemaVersion": 2,
          "instances": [
            { "instanceId": "g1", "moduleId": "test/gen/1.0.0", "enabled": true },
            { "instanceId": "g2", "moduleId": "test/gen/1.0.0", "enabled": true },
            { "instanceId": "s1", "moduleId": "test/sink/1.0.0", "enabled": true }
          ],
          "networks": [
            { "name": "bus", "isAutoGenerated": false, "sources": ["g1.out", "g2.out"], "targets": ["s1.in"] }
          ]
        }
        """);

        // 加载侧**没有 gen 包** ⇒ g1/g2 都成占位（无口）
        harness.Services.LoadComposite(path).Succeeded.ShouldBeTrue();
        harness.Services.GetInstances().Where(i => i.InstanceId is "g1" or "g2")
            .ShouldAllBe(i => i.IsPlaceholder);

        // 只补齐 g1 → g1 锚定、g2 仍悬空
        harness.Register("gen", typeof(GeneratorModule));
        var resolve1 = harness.Services.ResolvePlaceholder("g1", "test/gen/1.0.0");
        resolve1.Succeeded.ShouldBeTrue(resolve1.Failures.Count > 0 ? resolve1.Failures[0] : null);

        var network = harness.Services.GetNetworks().Single(n => n.Name == "bus");
        network.Sources.Count.ShouldBe(2, "**声明保留**：未锚定的源也在视图的源集合里（在场在前、悬空在后）");
        network.Sources.ShouldContain("g2.out");
        network.IsStalled.ShouldBeFalse("**部分源未锚定不是停流**（全部源未锚定才是）");

        var bindings = harness.Runtime.Bindings.Bindings.Where(b => b.Network.Name == "bus").ToList();
        bindings.Count.ShouldBe(1, "只有锚定的那个源建立绑定");
        bindings[0].Source.PortName.ShouldBe(GeneratorModule.OutPort);
        bindings[0].Source.InstanceId.ShouldBe("g1");

        harness.Runtime.Issues.Recent(30).ShouldContain(e =>
            e.Issue.Message.Contains("该源不参与投递", StringComparison.Ordinal)
            && e.Issue.Message.Contains("g2.out", StringComparison.Ordinal));

