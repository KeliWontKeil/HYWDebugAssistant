/// <summary>
/// **设计时替身运行时**（XAML 预览器与视图层单元测试用）：查询返回**样例数据**、命令返回成功且**无副作用**。
/// </summary>
/// <remarks>
/// <list type="bullet">
///   <item>它不是产品实现——只用于让 XAML 预览器与视图层测试能构造视图模型（UI 只依赖 <c>Core.Api</c>，
///     因此可以在此提供一个最小替身，而不必拉起整个框架）；</item>
///   <item>**【用户第九轮反馈】返回样例数据而非空集合**：否则设计器里列表全是空的，
