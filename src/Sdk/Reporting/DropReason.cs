namespace HYWDebugAssistant.Sdk.Reporting;

/// <summary>
/// **一条数据单元没有到达消费方的唯一原因词表**：框架按它记账，模块按同一套词表上报自己的丢弃。
/// </summary>
/// <remarks>
/// <para>
/// <b>为什么要有唯一词表</b>：丢弃必须分类。把"上游停流"这种**合法状态**和"队列满"这种**运行时丢弃**
/// 混成一个数，界面上就再也说不清"这条数据为什么没到"。三处记账共用本枚举，各自只回答自己那条轴上的事实：
/// </para>
/// <list type="bullet">
///   <item><b>队列轴</b>（每 (实例, 口) 的入站队列、每会话的接入队列）：
///     满队挤旧 / 满队拒新 / 过期清尾 / 停止清尾 / 超长单元；</item>
///   <item><b>流轴</b>（绑定投递的诊断计数）：停流 / 无承载 / 承载已停止 / 载荷非法；</item>
///   <item><b>会话轴</b>（一条外部接入会话）：会话未打开 / 写失败 / 会话队列满 / 适配件溢出。</item>
/// </list>
/// <para>
/// 数值**显式绑定**：词表会进诊断视图与读数，新增成员时不得改变已有成员的值。
/// </para>
/// </remarks>
public enum DropReason
{
    /// <summary>
    /// **停流未投递**：上游挂起（Disabled）或网络停流期间发布的数据报。
    /// </summary>
    /// <remarks>
    /// <b>由流轴记录</b>。<b>合法状态，不是丢</b>：停流是用户或框架主动造成的暂停，链路本身没有故障；
    /// 它**不得**并入"传输丢弃"合计，呈现上也按状态而非故障处理。
    /// </remarks>
    Stalled = 0,

    /// <summary>
    /// **队列满、挤掉最旧的单元**（丢旧策略：新单元入队，队头被挤出队列）。
    /// </summary>
    /// <remarks>
    /// <b>由队列轴记录</b>（流轴在投递时也会记一次，因为被挤掉的旧单元确实没有到达消费方）。
    /// 是**真的丢了一个单元**：本次投递成立，但被挤掉的那个不算送达。
    /// </remarks>
    QueueFullEvicted = 1,

    /// <summary>
    /// **队列满、拒绝新到的单元**（丢新策略：保留已有积压，本次入队失败）。
    /// </summary>
    /// <remarks><b>由队列轴记录</b>。真丢：本次单元没有进队列。</remarks>
    QueueFullRejected = 2,

    /// <summary>
    /// **无承载**：目标口不存在（未声明 / 已移除 / 从未建队列），该单元没有可投的队列。
    /// </summary>
    /// <remarks><b>由流轴记录</b>。真丢，且与"队列满"性质不同（不是容量问题，投到哪儿都不成立）。</remarks>
    NoCarrier = 3,

    /// <summary>
    /// **承载已停止**：目标实例的专属线程与队列正在拆除（已请求停止或已释放）。
    /// </summary>
    /// <remarks>
    /// <b>由流轴记录</b>。真丢：实例已不在运行，投递不成立。与 <see cref="NoCarrier"/> 分开，
    /// 是因为它表示"曾有承载、现在停了"——处置与排障方向都不同。
    /// </remarks>
    CarrierStopped = 4,

    /// <summary>
    /// **载荷非法**：载荷长度小于目标接收口契约要求的尺寸，无法按契约解释。
    /// </summary>
    /// <remarks><b>由流轴记录</b>。真丢（长度校验失败，补零会让下游读到伪造的值）。</remarks>
    InvalidPayload = 5,

    /// <summary>
    /// **过期**：单元在队列里停留超过允许的最大积压时长，被清出队列（清尾而不是送达）。
    /// </summary>
    /// <remarks>
    /// <b>由队列轴记录</b>。真丢：迟到的数据对实时监视没有价值，投给消费方只会让界面显示已过期的值。
    /// </remarks>
    Expired = 6,

    /// <summary>
    /// **停止 / 清空队列时丢弃**：队列里还没被消费的单元随承载拆除一起丢掉。
    /// </summary>
    /// <remarks>
    /// <b>由队列轴记录</b>。<b>属于丢弃，但不是故障</b>：消费方已经不存在，这些单元无处可去；
    /// 它不进任何"运行期丢包率"的分子，但仍要计数——否则"发出去的比收到的多"就永远对不上账。
    /// </remarks>
    DiscardedOnStop = 7,

    /// <summary>
    /// **模块内部丢弃**：模块自己决定不处理某个单元（业务上不适用、内部缓冲已满、解析失败等）。
    /// </summary>
    /// <remarks>
    /// <b>只能经模块上报口记录</b>（端口面的 <see cref="Context.IPortAccess.ReportLoss"/>
    /// 与外部接入面的上报），框架**不得**自行产生这个原因——传输与会话的事实归框架，
    /// 模块的内部判断归模块，两边不许互相冒充。
    /// </remarks>
    ModuleInternal = 8,

    /// <summary>
    /// **会话未打开**：向一条尚未处于打开态的外部接入写入（关闭 / 打开中 / 故障后未重开）。
    /// </summary>
    /// <remarks><b>由会话轴记录</b>。真丢：写根本没交给适配件。</remarks>
    SessionNotOpen = 9,

    /// <summary>
    /// **写失败**：适配件在写路径上返回失败或抛出（对端已断、设备被拔出等）。
    /// </summary>
    /// <remarks><b>由会话轴记录</b>。真丢：字节没有离开进程。</remarks>
    SessionWriteFailed = 10,

    /// <summary>
    /// **会话队列满、挤掉最旧的单元**（每会话一条接入队列的丢旧策略）。
    /// </summary>
    /// <remarks>
    /// <b>由会话轴记录</b>（接入队列满时）。与口队列的 <see cref="QueueFullEvicted"/> 分开：
    /// 两者的容量、拥有者与排障对象都不同，混在一起就查不出是哪一段堵了。
    /// </remarks>
    SessionQueueFullEvicted = 11,

    /// <summary>
    /// **会话队列满、拒绝新到的单元**（丢新策略）。
    /// </summary>
    /// <remarks><b>由会话轴记录</b>。真丢：本次原始字节没有进接入队列。</remarks>
    SessionQueueFullRejected = 12,

    /// <summary>
    /// **适配件溢出**：适配件自己的暂存队列满、数据报被截断或无法交付给框架。
    /// </summary>
    /// <remarks>
    /// <b>由会话轴记录</b>（适配件经回报面上报）。真丢，且**不应发生**——它是适配件的容量配置信号，
    /// 不是框架的丢弃策略在起作用。
    /// </remarks>
    AdapterOverflow = 13,

    /// <summary>
    /// **超长单元**：单元长度超过接收方缓冲或声明的单单元上限，装不下。
    /// </summary>
    /// <remarks>
    /// <b>由队列轴与会话轴记录</b>（谁发现装不下谁记）。真丢：**绝不截断交付**——
    /// 截断后下游会把半条数据当成完整数据解释。
    /// </remarks>
    OversizedUnit = 14,

    /// <summary>
    /// **发送积压丢失**：会话发送积压满时挤掉最旧单元，或单个单元超过整个积压容量（防御）。
    /// </summary>
    /// <remarks>
    /// <b>由会话轴记录</b>（写泵的入队路径）。它只发生在设备写入长期跟不上报价时；
    /// 积压的过期与关闭清空分别按 <see cref="Expired"/> 与 <see cref="DiscardedOnStop"/> 记账。
    /// </remarks>
    SendBacklogEvicted = 15,
}
