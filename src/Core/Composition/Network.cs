using HYWDebugAssistant.Sdk.Ports;

namespace HYWDebugAssistant.Core.Composition;

/// <summary>网络成员：一个实例上的一个口。</summary>
/// <param name="InstanceId">实例 ID。</param>
/// <param name="PortName">口名。</param>
/// <param name="Direction">方向（源 = 发送口；宿 = 接收口）。</param>
public readonly record struct NetworkMember(string InstanceId, string PortName, PortDirection Direction)
{
    /// <inheritdoc />
    public override string ToString() => $"{InstanceId}.{PortName}";
}

/// <summary>
/// 网络：**连接的统一模型**（直连 = 匿名网络，标签 = 命名网络）——主文档 §6.3。
/// </summary>
/// <remarks>
/// <list type="bullet">
///   <item>网络**严格单向**：源 = 发送口集合，宿 = 接收口集合（**N:M**；无运行时转发对象）；</item>
///   <item><b>多源是一等组合</b>：同名标签下出现多个发送端 ⇒ **一条多源网络**，
///     源集合 = 全部发送口、宿集合 = **与任一源兼容**的接收口之并集。投递**逐 (源,宿) 对**建立绑定
///     （只排除不兼容的那一对，M6）；接收侧**按到达顺序**（框架中立，不做跨源排序，M4b）；</item>
///   <item><see cref="Sources"/> 是**声明的源集合**：加载期"口/实例不存在"的源以**字面量留着**
///     等补齐后重锚（`ModuleRuntime.Persistence`）。**"在场"由绑定集合表达**（`RuntimeBinding.Source`
///     逐源一条）——加载降级态下 <see cref="Sources"/> 可以含未锚定的成员，这是设计而非缺陷；</item>
///   <item><see cref="IsStalled"/> = **全部源都未锚定**（加载期降级态）：声明保留、不参与绑定、不投递。
///     **部分源未锚定不是停流**——其余源照常投递，只对该源报 Issue；</item>
///   <item>派生网络（标签/几何）标记 <see cref="IsAutoGenerated"/>。</item>
/// </list>
/// </remarks>
public sealed class Network
{
    /// <summary>创建单源网络（兼容重载）。</summary>
    /// <param name="name">网络名（匿名网络为空串）。</param>
    /// <param name="source">源成员（发送口）。</param>
    /// <param name="targets">宿成员（接收口，1:N）。</param>
    /// <param name="isAutoGenerated">是否由派生（标签/几何）生成。</param>
    /// <param name="unresolvedMembers">
    /// **悬空成员**：加载重锚时口/实例不存在的宿成员——保留声明、不参与绑定（§9.3 PQ-PS-04）。
    /// </param>
    public Network(
        string name,
        NetworkMember source,
        IReadOnlyList<NetworkMember> targets,
        bool isAutoGenerated = false,
        IReadOnlyList<NetworkMember>? unresolvedMembers = null)
        : this(name, [source], targets, isAutoGenerated, unresolvedMembers)
    {
    }

    /// <summary>
    /// 创建**多源**网络：源集合 N ≥ 0、宿集合 M ≥ 0（N:M）；N + 未锚定源数 ≥ 1。
    /// </summary>
    /// <param name="name">网络名（匿名网络为空串）。</param>
    /// <param name="sources">
    /// **在场（已锚定）的源成员**（发送口）——多源是**合法的一等组合**（同名标签多发送端即此形态）。
    /// **可为空**：空 = 全部源都未锚定 = <see cref="IsStalled"/>（加载降级态）。
    /// </param>
    /// <param name="targets">在场（已锚定）的宿成员（接收口，1:N / N:M）。</param>
    /// <param name="isAutoGenerated">是否由派生（标签/几何）生成。</param>
    /// <param name="unresolvedMembers">**悬空的宿成员**（加载重锚失败的宿——声明保留）。</param>
    /// <param name="unresolvedSources">**悬空的源成员**（加载重锚失败的源——声明保留；方向 = 发送）。</param>
    public Network(
        string name,
        IReadOnlyList<NetworkMember> sources,
        IReadOnlyList<NetworkMember> targets,
        bool isAutoGenerated = false,
        IReadOnlyList<NetworkMember>? unresolvedMembers = null,
        IReadOnlyList<NetworkMember>? unresolvedSources = null,
        bool allowUnverifiedTypeMatch = false)
    {
        ArgumentNullException.ThrowIfNull(sources);
        ArgumentNullException.ThrowIfNull(targets);

        Name = name ?? string.Empty;
        Sources = sources;
        Targets = targets;
        IsAutoGenerated = isAutoGenerated;
        UnresolvedMembers = unresolvedMembers ?? [];
        UnresolvedSources = unresolvedSources ?? [];
        AllowUnverifiedTypeMatch = allowUnverifiedTypeMatch;

        // 不变量：**声明的源至少有一个**（在场或悬空）——没有源的"网络"不是网络
        if (Sources.Count == 0 && UnresolvedSources.Count == 0)
        {
            throw new ArgumentException("网络至少需要一个源成员（在场或悬空）", nameof(sources));
        }
    }

    /// <summary>网络名（匿名网络为空串；命名网络为用户名或自动名 <c>net-N</c>）。</summary>
    public string Name { get; }

    /// <summary>是否命名网络（直连 = 匿名网络）。</summary>
    public bool IsNamed => Name.Length > 0;

    /// <summary>是否由快速建网自动生成。</summary>
    public bool IsAutoGenerated { get; }

    /// <summary>
    /// 本条连接是否带**用户显式确认**的"允许数据类型标识不同"强连。
    /// </summary>
    /// <remarks>
    /// <list type="bullet">
    ///   <item>**默认 false**：不同标识 = 框架无资格判定 ⇒ 不兼容（派生网络没有"用户确认"这一步，恒为 false）；</item>
    ///   <item>true 只影响**兼容判定**（放行 + 留警示），**不改变**投递语义与顺序保证；</item>
    ///   <item>它是**用户决定**而非派生事实 ⇒ 随组合件保存（否则重载后连接会莫名失效）。</item>
    /// </list>
    /// </remarks>
    public bool AllowUnverifiedTypeMatch { get; }

    /// <summary>
    /// **在场的源成员集合**：**多源合法**（同名标签的多个发送端同属一条网络）。
    /// </summary>
    /// <remarks>
    /// <list type="bullet">
    ///   <item>投递按 **逐 (源, 宿) 对** 建立绑定；每个绑定携带**它自己的源**与该源的契约布局、诊断计数
    ///     （⇒ 丢弃/速率**天然按源归属**）；</item>
    ///   <item><b>"在场"是这里的定义</b>：加载期未锚定的源在 <see cref="UnresolvedSources"/> 里（声明保留），
    ///     不在本集合；所有源都未锚定时本集合为空且 <see cref="IsStalled"/> 为真；</item>
    ///   <item>空集合是**合法状态**（停流），不是错误——读取方必须先看 <see cref="IsStalled"/>。</item>
    /// </list>
    /// </remarks>
    public IReadOnlyList<NetworkMember> Sources { get; }

    /// <summary>
    /// **主源**（首个在场的源；停流时回落首个**未锚定的声明源**）。
    /// </summary>
    /// <remarks>
    /// **兼容旧代码的便捷访问器**：多源场景**不要**用它做判定或展示——判定用 <see cref="Sources"/>，
    /// 展示/归属用绑定集合或 <see cref="DeclaredSources"/>。
    /// </remarks>
    public NetworkMember Source => Sources.Count > 0 ? Sources[0]
        : UnresolvedSources.Count > 0 ? UnresolvedSources[0]
        : default;

    /// <summary>在场的宿成员（接收口）。</summary>
    public IReadOnlyList<NetworkMember> Targets { get; }

    /// <summary>
    /// 是否停流（**全部声明的源都未锚定**）。
    /// </summary>
    /// <remarks>
    /// <b>派生量，不单独存</b>（⇒ 不存在"标志与成员不一致"的可能）：<c>IsStalled ⇔ Sources.Count == 0</c>。
    /// **部分源未锚定不算停流**——其余源照常投递，只对该源报 Issue。
    /// </remarks>
    public bool IsStalled => Sources.Count == 0;

    /// <summary>
    /// **悬空的宿成员**（加载重锚失败）：**保留声明与 Issue**，不建立绑定，其余部分照常运行（§9.3）。
    /// </summary>
    /// <remarks>
    /// 悬空是加载期的**降级态**而非正常编辑态——手动建网时口不存在会直接拒绝，不会产生悬空成员。
    /// 占位实例被解析（<c>ResolvePlaceholder</c>）或口补齐后，成员会被重新锚定。
    /// </remarks>
    public IReadOnlyList<NetworkMember> UnresolvedMembers { get; }

    /// <summary>
    /// **悬空的源成员**（加载重锚失败）：与 <see cref="UnresolvedMembers"/> 对称的**源侧**声明保留。
    /// </summary>
    /// <remarks>
    /// 方向恒为 <see cref="PortDirection.Send"/>（重锚按此方向找口）。**部分源悬空不影响其余源投递**；
    /// 全部源悬空 = <see cref="IsStalled"/>。
    /// </remarks>
    public IReadOnlyList<NetworkMember> UnresolvedSources { get; }

    /// <summary>**全部声明的源**（在场在前，悬空在后）——持久化与展示的事实源。</summary>
    public IReadOnlyList<NetworkMember> DeclaredSources => [.. Sources, .. UnresolvedSources];

    /// <summary>全部成员（**源在前**：在场源、悬空源、宿、悬空宿）。</summary>
    public IReadOnlyList<NetworkMember> Members =>
        [.. Sources, .. UnresolvedSources, .. Targets, .. UnresolvedMembers];

    /// <summary>
    /// 以新的成员关系产生等价网络（**成员变化一律换新对象**：绑定快照要求网络不可变，§4.2）。
    /// </summary>
    /// <remarks>单源重载（兼容）；成员重锚会换新对象，见 <c>ModuleRuntime.Persistence</c>。</remarks>
    public Network WithMembership(
        NetworkMember source,
        IReadOnlyList<NetworkMember> targets,
        IReadOnlyList<NetworkMember> unresolvedMembers) =>
        WithMembership([source], targets, unresolvedMembers, []);

    /// <summary>以新的**多源**成员关系产生等价网络。</summary>
    /// <param name="sources">**在场**的源成员集合（可为空 = 停流）。</param>
    /// <param name="targets">在场的宿成员集合。</param>
    /// <param name="unresolvedMembers">悬空的宿成员。</param>
    /// <param name="unresolvedSources">悬空的源成员。</param>
    /// <returns>新网络对象。</returns>
    public Network WithMembership(
        IReadOnlyList<NetworkMember> sources,
        IReadOnlyList<NetworkMember> targets,
        IReadOnlyList<NetworkMember> unresolvedMembers,
        IReadOnlyList<NetworkMember> unresolvedSources)
    {
        ArgumentNullException.ThrowIfNull(sources);
        ArgumentNullException.ThrowIfNull(targets);
        ArgumentNullException.ThrowIfNull(unresolvedMembers);
        ArgumentNullException.ThrowIfNull(unresolvedSources);

        return new Network(
            Name, sources, targets, IsAutoGenerated, unresolvedMembers, unresolvedSources, AllowUnverifiedTypeMatch);
    }

    /// <inheritdoc />
    public override string ToString() => IsNamed
        ? $"{Name}（{DeclaredSources.Count} 源 → {Targets.Count} 宿）"
        : $"(匿名) {string.Join("、", DeclaredSources)} → {Targets.Count}";
}
