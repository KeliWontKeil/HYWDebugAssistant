using System.Globalization;
using System.Text.Json.Nodes;
using HYWDebugAssistant.Core.Api;
using HYWDebugAssistant.Core.Composition;
using HYWDebugAssistant.Sdk.Ports;

namespace HYWDebugAssistant.Core.Persistence;

/// <summary>
/// 组合件的文本形态：JSON 对象 ↔ <see cref="Composite"/>（R4-5 / R4-6 / C3-3）。
/// </summary>
/// <remarks>
/// <list type="bullet">
///   <item><b>白名单字段 + 不猜测</b>：只读取已知字段名；未识别字段**不解释、只保留**（按层保留原始片段）；</item>
///   <item><b>未知字段保留（C3-3）</b>：加载时留下根/实例/网络/布局/配置各层的原始片段，保存时**合并**——
///     已知字段按当前 Schema 写、未识别字段原样带回 → AC-4 无损往返；</item>
///   <item><b>部分恢复</b>：单条记录不合法 → **跳过该条 + 警告**，其余照常解析（§9.3"损坏 → 尽量部分恢复"）；
///     结构性违规（根不是对象 / 版本非法 / 段类型错误）→ 由调用方拒绝整个文件；</item>
///   <item><b>不含运行态</b>：绑定、队列、Runtime State 一律不序列化（§9.2）。</item>
/// </list>
/// </remarks>
public static class CompositeSerializer
{
    private const string SchemaVersionName = "schemaVersion";
    private const string NameField = "name";
    private const string SavedAtField = "savedAt";
    private const string InstancesField = "instances";
    private const string NetworksField = "networks";
    private const string LayoutField = "layout";
    private const string InstanceIdField = "instanceId";
    private const string ModuleIdField = "moduleId";
    private const string EnabledField = "enabled";
    private const string ConfigurationField = "configuration";
    private const string PortsField = "ports";
    private const string OffsetField = "offset";
    private const string LockedField = "locked";

    /// <summary>
    /// **用户拖动后的挂载边覆盖**（G5 · C5-7）——只在**非 `Auto`** 时写出（"缺省不写"纪律）。
    /// </summary>
    /// <remarks>
    /// **与 <see cref="LockedField"/> 的分工**：`locked` = 锚点「**固定**」（不可拖动）—— **字段名沿用旧值**以兼容既有组合件；
    /// 本字段 = 边覆盖。老组合件没有 `edge` ⇒ 回落到**模块声明的默认边**（未知字段保留 + 缺省即默认，无需迁移分支）。
    /// </remarks>
    private const string EdgeField = "edge";

    private const string LabelField = "label";
    private const string AutoGeneratedField = "isAutoGenerated";
    private const string AllowUnverifiedField = "allowUnverifiedTypeMatch";
    private const string SourcesField = "sources";
    private const string LegacySourceField = "source";
    private const string TargetsField = "targets";
    private const string UnresolvedField = "unresolved";
    private const string XField = "x";
    private const string YField = "y";
    private const string WidthField = "width";
    private const string HeightField = "height";
    private const string ViewVisibleField = "viewVisible";

    /// <summary>
    /// 解析组合件（**容错**：记录级问题跳过 + 警告）。
    /// </summary>
    /// <param name="root">根 JSON 对象。</param>
    /// <param name="warnings">记录级问题（面向用户，由调用方转 Issue）。</param>
    /// <param name="failure">结构性失败原因（非空 = 应拒绝加载）。</param>
    /// <param name="dipScale">
    /// **当前屏幕缩放**（≤0 视为 1）。只用于把**旧格式**（&lt; v3）里的布局数值从
    /// 屏幕物理像素换算成 DIP —— v3 起四个数已经是 DIP，本参数无用。
    /// </param>
    public static bool TryParse(
        JsonObject root,
        out Composite? composite,
        out IReadOnlyList<string> warnings,
        out string? failure,
        double dipScale = 1.0)
    {
        ArgumentNullException.ThrowIfNull(root);

        composite = null;
        failure = null;
        var issues = new List<string>();

        if (!TryReadInt(root, SchemaVersionName, out var schemaVersion) || schemaVersion < 1)
        {
            failure = $"缺少或非法的 {SchemaVersionName}（组合件必须内嵌 Schema 版本，§9.3）";
            warnings = issues;
            return false;
        }

        if (root[InstancesField] is not null and not JsonArray)
        {
            failure = $"{InstancesField} 必须是数组";
            warnings = issues;
            return false;
        }

        if (root[NetworksField] is not null and not JsonArray)
        {
            failure = $"{NetworksField} 必须是数组";
            warnings = issues;
            return false;
        }

        if (root[LayoutField] is not null and not JsonObject)
        {
            failure = $"{LayoutField} 必须是对象（键 = 实例 ID）";
            warnings = issues;
            return false;
        }

        var instances = new List<CompositeInstanceRecord>();
        var seenInstanceIds = new HashSet<string>(StringComparer.Ordinal);

        foreach (var node in root[InstancesField] as JsonArray ?? [])
        {
            if (node is not JsonObject entry)
            {
                issues.Add($"{InstancesField} 中存在非对象项（已跳过）");
                continue;
            }

            var instanceId = ReadString(entry, InstanceIdField);
            if (string.IsNullOrWhiteSpace(instanceId))
            {
                issues.Add($"{InstancesField} 中存在缺少 {InstanceIdField} 的项（已跳过）");
                continue;
            }

            if (!seenInstanceIds.Add(instanceId))
            {
                issues.Add($"实例 ID 重复：{instanceId}（重复项已跳过）");
                continue;
            }

            var moduleId = ReadString(entry, ModuleIdField);
            if (string.IsNullOrWhiteSpace(moduleId) || !Sdk.ModuleId.TryParse(moduleId, out _))
            {
                issues.Add($"实例 {instanceId} 的 {ModuleIdField} 非法：'{moduleId}'（该项已跳过）");
                continue;
            }

            instances.Add(new CompositeInstanceRecord
            {
                InstanceId = instanceId,
                ModuleId = moduleId,
                Enabled = ReadBool(entry, EnabledField, fallback: true),
                Configuration = entry[ConfigurationField] as JsonObject,
                Ports = ReadPorts(entry, instanceId, issues),
                Fragment = entry,
            });
        }

        var networks = new List<CompositeNetworkRecord>();
        var seenNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (var node in root[NetworksField] as JsonArray ?? [])
        {
            if (node is not JsonObject entry)
            {
                issues.Add($"{NetworksField} 中存在非对象项（已跳过）");
                continue;
            }

            var name = ReadString(entry, NameField) ?? string.Empty;
            if (name.Length > 0 && !seenNames.Add(name))
            {
                issues.Add($"网络名重复：{name}（重复项已跳过）");
                continue;
            }

            var sources = ReadSources(entry, name, issues);
            if (sources.Count == 0)
            {
                issues.Add($"网络 '{Describe(name)}' 没有合法的 {SourcesField}（该项已跳过）");
                continue;
            }

            var targets = new List<string>();
            var targetsValid = true;
            foreach (var targetNode in entry[TargetsField] as JsonArray ?? [])
            {
                var target = targetNode?.ToString();
                if (!TryParseMember(target, out _))
                {
                    issues.Add($"网络 '{Describe(name)}' 的宿成员非法：'{target}'（该项已跳过）");
                    targetsValid = false;
                    break;
                }

                targets.Add(target!);
            }

            if (!targetsValid)
            {
                continue;
            }

            var unresolved = new List<string>();
            foreach (var unresolvedNode in entry[UnresolvedField] as JsonArray ?? [])
            {
                var member = unresolvedNode?.ToString();
                if (TryParseMember(member, out _))
                {
                    unresolved.Add(member!);
                }
                else
                {
                    issues.Add($"网络 '{Describe(name)}' 的悬空成员非法：'{member}'（已忽略）");
                }
            }

            networks.Add(new CompositeNetworkRecord
            {
                Name = name,
                IsAutoGenerated = ReadBool(entry, AutoGeneratedField, fallback: false),
                AllowUnverifiedTypeMatch = ReadBool(entry, AllowUnverifiedField, fallback: false),
                Sources = sources,
                Targets = targets,
                Unresolved = unresolved,
                Fragment = entry,
            });
        }

        // **旧格式的单位归一（唯一一处）**：v3 之前 `layout.*` 的四个数是**屏幕物理像素**，
        // 而模型自 v3 起一律 DIP（见 `ModuleLayoutView`）⇒ 在这里 ÷ 缩放换过来。
        // 放在解析期而不是下游，是为了让"`ModuleLayoutView` 就是 DIP"成为**无条件的不变式** ——
        // 读它的代码（视图模型、DockRule、呈现）不需要知道单位来源，也不带任何"要不要换算"的标记。
        var layoutScale = schemaVersion < 3 && dipScale > 0 ? dipScale : 1.0;

        var layout = new List<ModuleLayoutView>();
        if (root[LayoutField] is JsonObject layoutObject)
        {
            foreach (var (instanceId, value) in layoutObject)
            {
                if (value is not JsonObject item)
                {
                    issues.Add($"{LayoutField} 中 {instanceId} 不是对象（已跳过）");
                    continue;
                }

                if (!TryReadDouble(item, XField, out var x) || !TryReadDouble(item, YField, out var y))
                {
                    issues.Add($"{LayoutField} 中 {instanceId} 缺少数值 {XField}/{YField}（已跳过）");
                    continue;
                }

                layout.Add(new ModuleLayoutView(
                    instanceId,
                    x / layoutScale,
                    y / layoutScale,
                    ReadDouble(item, WidthField, fallback: 0) / layoutScale,
                    ReadDouble(item, HeightField, fallback: 0) / layoutScale,
                    ReadBool(item, ViewVisibleField, fallback: true)));
            }
        }

        composite = new Composite
        {
            SchemaVersion = schemaVersion,
            Name = ReadString(root, NameField) ?? string.Empty,
            SavedAt = TryReadDateTimeOffset(root, SavedAtField, out var savedAt) ? savedAt : DateTimeOffset.Now,
            Instances = instances,
            Networks = networks,
            Layout = layout,
            RootFragment = root,
        };

        warnings = issues;
        return true;
    }

    /// <summary>
    /// 生成组合件的文本形态（**合并未知字段**：已知字段按当前 Schema 写，未识别字段原样带回）。
    /// </summary>
    /// <remarks>
    /// 片段一律**深拷贝后再挂载**：JSON 节点只能有一个父节点，复用原节点会抛
    /// "node already has a parent"（原片段仍在旧数组里）。
    /// </remarks>
    public static JsonObject ToJsonObject(Composite composite)
    {
        ArgumentNullException.ThrowIfNull(composite);

        // 以加载时的根片段为底稿（若来自加载）→ 未识别字段原样保留
        var root = composite.RootFragment ?? new JsonObject();

        root[SchemaVersionName] = Composite.CurrentSchemaVersion;
        root[NameField] = composite.Name;
        root[SavedAtField] = composite.SavedAt.ToString("o", CultureInfo.InvariantCulture);

        var fragmentsById = new Dictionary<string, JsonObject>(StringComparer.Ordinal);
        foreach (var record in composite.Instances)
        {
            if (record.Fragment is not null)
            {
                fragmentsById.TryAdd(record.InstanceId, record.Fragment);
            }
        }

        var instances = new JsonArray();
        foreach (var record in composite.Instances)
        {
            var entry = fragmentsById.TryGetValue(record.InstanceId, out var fragment)
                ? (JsonObject)fragment.DeepClone()
                : new JsonObject();

            entry[InstanceIdField] = record.InstanceId;
            entry[ModuleIdField] = record.ModuleId;
            entry[EnabledField] = record.Enabled;

            if (record.Configuration is null || record.Configuration.Count == 0)
            {
                _ = entry.Remove(ConfigurationField);
            }
            else
            {
                entry[ConfigurationField] = record.Configuration.DeepClone();
            }

            if (record.Ports.Count == 0)
            {
                _ = entry.Remove(PortsField);
            }
            else
            {
                var ports = entry[PortsField] as JsonObject ?? new JsonObject();
                var known = new HashSet<string>(StringComparer.Ordinal);
                foreach (var port in record.Ports)
                {
                    known.Add(port.PortName);
                    var portNode = ports[port.PortName] as JsonObject ?? new JsonObject();
                    portNode[OffsetField] = port.Offset;

                    // 【G5 · C5-7】「固定」是**三态**：null = 用户没设置过 ⇒ **缺省不写**（该口是否可拖由
                    // 模块 `PortDeclaration.AnchorDraggable` 决定）；有值才写（用户设过 ⇒ 覆盖模块声明）。
                    if (port.IsAnchorFixed is { } anchorFixed)
                    {
                        portNode[LockedField] = anchorFixed;
                    }
                    else
                    {
                        _ = portNode.Remove(LockedField);
                    }

                    // 【G5】边覆盖：只在**非 Auto** 时写出（"缺省不写" ⇒ 老文件与新文件都干净）
                    if (port.Edge == HYWDebugAssistant.Sdk.Ports.PortEdge.Auto)
                    {
                        _ = portNode.Remove(EdgeField);
                    }
                    else
                    {
                        portNode[EdgeField] = port.Edge.ToString();
                    }

                    // 空标签 = 移除该字段（保持文件干净），而非写入 null
                    if (string.IsNullOrWhiteSpace(port.Label))
                    {
                        _ = portNode.Remove(LabelField);
                    }
                    else
                    {
                        portNode[LabelField] = port.Label;
                    }
                    ports[port.PortName] = portNode;
                }

                RemoveUnlisted(ports, known);
                entry[PortsField] = ports;
            }

            instances.Add(entry);
        }

        root[InstancesField] = instances;

        var networkFragments = MatchNetworkFragments(composite);
        var networks = new JsonArray();
        foreach (var record in composite.Networks)
        {
            var entry = networkFragments.Count > 0 ? networkFragments.Dequeue() : new JsonObject();
            entry[NameField] = record.Name;
            entry[AutoGeneratedField] = record.IsAutoGenerated;
            entry[SourcesField] = ToJsonArray(record.Sources);

            // 单源字段**必须清掉**：与 `sources` 并存 = 同一事实两个字段（第二事实源）
            _ = entry.Remove(LegacySourceField);

            entry[TargetsField] = ToJsonArray(record.Targets);
            entry[UnresolvedField] = ToJsonArray(record.Unresolved);

            // **可加性**：只在用户确认真是 true 时写出（缺省 = false），保持文件干净
            if (record.AllowUnverifiedTypeMatch)
            {
                entry[AllowUnverifiedField] = true;
            }
            else
            {
                _ = entry.Remove(AllowUnverifiedField);
            }

            networks.Add(entry);
        }

        root[NetworksField] = networks;

        var layoutRoot = root[LayoutField] as JsonObject ?? new JsonObject();
        var layoutKeys = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in composite.Layout)
        {
            layoutKeys.Add(item.InstanceId);
            var layoutNode = layoutRoot[item.InstanceId] as JsonObject ?? new JsonObject();
            layoutNode[XField] = item.X;
            layoutNode[YField] = item.Y;
            layoutNode[WidthField] = item.Width;
            layoutNode[HeightField] = item.Height;
            layoutNode[ViewVisibleField] = item.IsViewVisible;
            layoutRoot[item.InstanceId] = layoutNode;
        }

        RemoveUnlisted(layoutRoot, layoutKeys);
        root[LayoutField] = layoutRoot;

        return root;
    }

