    /// <summary>拼装成员字面量 <c>实例ID.口名</c>（锚定与诊断的唯一写法）。</summary>
    public static string FormatMember(string instanceId, string portName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(instanceId);
        ArgumentException.ThrowIfNullOrWhiteSpace(portName);

        return $"{instanceId}.{portName}";
    }

    /// <summary>
    /// 解析成员字面量 <c>实例ID.口名</c>（**按最后一个点切分**：实例 ID 允许含点）。
    /// </summary>
    public static bool TryParseMember(string? literal, out NetworkMember member)
    {
        member = default;

        if (string.IsNullOrWhiteSpace(literal))
        {
            return false;
        }

        var separator = literal.LastIndexOf('.');
        if (separator <= 0 || separator == literal.Length - 1)
        {
            return false;
        }

        // 方向在重锚时按口声明校正，此处只承载名字（避免把方向写进文件成为第二事实源）
        member = new NetworkMember(literal[..separator], literal[(separator + 1)..], PortDirection.Receive);
        return true;
    }

    // ---------------------------------------------------------------- 内部

    private static JsonArray ToJsonArray(IReadOnlyList<string> values)
    {
        var array = new JsonArray();
        foreach (var value in values)
        {
            array.Add(value);
        }

        return array;
    }

    /// <summary>
    /// 网络片段按"命名优先、匿名按源+宿集合"匹配（匿名网络没有唯一名，不能只按名字配对）；
    /// 返回的片段已深拷贝（可安全挂到新数组）。
    /// </summary>
    private static Queue<JsonObject> MatchNetworkFragments(Composite composite)
    {
        var pool = composite.Networks
            .Where(r => r.Fragment is not null)
            .Select(r => r.Fragment!)
            .ToList();

        var matched = new Queue<JsonObject>();
        var consumed = new HashSet<JsonObject>(ReferenceEqualityComparer.Instance);

        foreach (var record in composite.Networks)
        {
            JsonObject? found = null;

            if (record.Name.Length > 0)
            {
                found = pool.FirstOrDefault(f =>
                    !consumed.Contains(f)
                    && string.Equals(ReadString(f, NameField), record.Name, StringComparison.Ordinal));
            }

            found ??= pool.FirstOrDefault(f =>
                !consumed.Contains(f)
                && string.Equals(ReadString(f, NameField) ?? string.Empty, record.Name, StringComparison.Ordinal)
                && SameSources(f, record.Sources)
                && SameTargets(f, record.Targets));

            if (found is not null)
            {
                _ = consumed.Add(found);
            }

            matched.Enqueue(found is null ? new JsonObject() : (JsonObject)found.DeepClone());
        }

        return matched;
    }

    /// <summary>
    /// 读入网络的**源成员集合**（schemaVersion 2 + **v1 兼容**）。
    /// </summary>
    /// <remarks>
    /// <list type="bullet">
    ///   <item>v1 的单源字符串字段 <c>source</c> 读出即**归一**为单元素集合（迁移在解析期完成）；</item>
    ///   <item>两个字段同时存在 ⇒ **以 <c>sources</c> 为准**并报警（不猜测、也不静默取旧值）；</item>
    ///   <item>非法项**逐项跳过 + 报警**（部分恢复），与宿/悬空成员同一策略。</item>
    /// </list>
    /// </remarks>
    private static List<string> ReadSources(JsonObject entry, string name, List<string> issues)
    {
        var sources = new List<string>();

        foreach (var node in entry[SourcesField] as JsonArray ?? [])
        {
            var literal = node?.ToString();
            if (TryParseMember(literal, out _))
            {
                sources.Add(literal!);
            }
            else
            {
                issues.Add($"网络 '{Describe(name)}' 的源成员非法：'{literal}'（该项已跳过）");
            }
        }

        var legacy = ReadString(entry, LegacySourceField);
        if (legacy is null)
        {
            return sources;
        }

        if (sources.Count > 0)
        {
            issues.Add($"网络 '{Describe(name)}' 同时含 {SourcesField} 与旧版 {LegacySourceField}"
                + $"（**以 {SourcesField} 为准**；保存时旧字段会被移除）");
            return sources;
        }

        if (TryParseMember(legacy, out _))
        {
            sources.Add(legacy);
        }
        else
        {
            issues.Add($"网络 '{Describe(name)}' 的旧版 {LegacySourceField} 非法：'{legacy}'（该项已跳过）");
        }

        return sources;
    }

    /// <summary>片段里的源集合（v2 数组优先，回落 v1 单源字符串）——匿名网络的片段配对用。</summary>
    private static List<string> FragmentSources(JsonObject fragment)
    {
        var array = (fragment[SourcesField] as JsonArray)?.Select(n => n?.ToString() ?? string.Empty).ToList();
        if (array is { Count: > 0 })
        {
            return array;
        }

        return ReadString(fragment, LegacySourceField) is { Length: > 0 } legacy ? [legacy] : [];
    }

    private static bool SameSources(JsonObject fragment, IReadOnlyList<string> sources) =>
        FragmentSources(fragment).OrderBy(s => s, StringComparer.Ordinal)
            .SequenceEqual(sources.OrderBy(s => s, StringComparer.Ordinal));

    private static bool SameTargets(JsonObject fragment, IReadOnlyList<string> targets)
    {
        var existing = (fragment[TargetsField] as JsonArray)?.Select(n => n?.ToString() ?? string.Empty).ToList() ?? [];
        return existing.Count == targets.Count
            && existing.OrderBy(t => t, StringComparer.Ordinal).SequenceEqual(targets.OrderBy(t => t, StringComparer.Ordinal));
    }

    private static void RemoveUnlisted(JsonObject container, HashSet<string> keep)
    {
        foreach (var key in container.Select(pair => pair.Key).Where(key => !keep.Contains(key)).ToList())
        {
            _ = container.Remove(key);
        }
    }

    private static string Describe(string name) => name.Length > 0 ? name : "(匿名)";

    private static string? ReadString(JsonObject root, string name) =>
        root.TryGetPropertyValue(name, out var node) && node is JsonValue value && value.TryGetValue(out string? text)
            ? text
            : null;

    /// <summary>空白标签归一为 null（空标签与未设置标签语义一致，不得进入运行时状态）。</summary>
    private static string? NormalizeLabel(string? text) => string.IsNullOrWhiteSpace(text) ? null : text;

    private static bool ReadBool(JsonObject root, string name, bool fallback) =>
        root.TryGetPropertyValue(name, out var node) && node is JsonValue value && value.TryGetValue(out bool parsed)
            ? parsed
            : fallback;

    /// <summary>读三态布尔（缺失 / 非布尔 ⇒ <see langword="null"/> = 未设置）。</summary>
    /// <param name="root">所在对象。</param>
    /// <param name="name">字段名。</param>
    private static bool? ReadBoolOrNull(JsonObject root, string name) =>
        root.TryGetPropertyValue(name, out var node) && node is JsonValue value && value.TryGetValue(out bool parsed)
            ? parsed
            : null;

    private static bool TryReadInt(JsonObject root, string name, out int result)
    {
        result = 0;
        return root.TryGetPropertyValue(name, out var node) && node is JsonValue value && value.TryGetValue(out result);
    }

    private static bool TryReadDouble(JsonObject root, string name, out double result)
    {
        result = 0;
        return root.TryGetPropertyValue(name, out var node) && node is JsonValue value && value.TryGetValue(out result);
    }

    private static double ReadDouble(JsonObject root, string name, double fallback) =>
        TryReadDouble(root, name, out var value) ? value : fallback;

    private static bool TryReadDateTimeOffset(JsonObject root, string name, out DateTimeOffset result)
    {
        result = default;
        return root.TryGetPropertyValue(name, out var node)
            && node is JsonValue value
            && value.TryGetValue(out string? text)
            && DateTimeOffset.TryParse(text, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind, out result);
    }

    /// <summary>读端口几何的**边覆盖**（G5）：缺失 / 非法 ⇒ `Auto`（= 无覆盖，回落到模块声明的默认边）。</summary>
    /// <param name="geometry">端口几何节点。</param>
    private static HYWDebugAssistant.Sdk.Ports.PortEdge ReadEdge(JsonObject geometry) =>
        ReadString(geometry, EdgeField) is { Length: > 0 } text
        && Enum.TryParse<HYWDebugAssistant.Sdk.Ports.PortEdge>(text, ignoreCase: true, out var edge)
            ? edge
            : HYWDebugAssistant.Sdk.Ports.PortEdge.Auto;

    private static List<PortGeometryView> ReadPorts(JsonObject entry, string instanceId, List<string> issues)
    {
        if (entry[PortsField] is not JsonObject ports)
        {
            return [];
        }

        var result = new List<PortGeometryView>(ports.Count);
        foreach (var (portName, value) in ports)
        {
            if (portName.Length == 0)
            {
                issues.Add($"实例 {instanceId} 存在空端口名的几何记录（已跳过）");
                continue;
            }

            if (value is not JsonObject geometry)
            {
                issues.Add($"实例 {instanceId} 的端口 {portName} 几何不是对象（已跳过）");
                continue;
            }

            result.Add(new PortGeometryView(
                portName,
                ReadDouble(geometry, OffsetField, fallback: 0.5),
                // 【G5】`locked` 缺失 = **用户没设置过**（不是"未固定"）⇒ 保持 null，交由模块声明决定
                ReadBoolOrNull(geometry, LockedField),
                NormalizeLabel(ReadString(geometry, LabelField)),
                ReadEdge(geometry)));
        }

        return result;
    }
