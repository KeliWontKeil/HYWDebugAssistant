using System.Text.Json.Nodes;
using HYWDebugAssistant.Core.Api;

namespace HYWDebugAssistant.Core.Persistence;

/// <summary>
/// **组合件**（Composite / 蓝图）：持久化与复用的**唯一载体**——主文档 §9.2 / ADR-0016。
/// </summary>
/// <remarks>
/// <list type="bullet">
///   <item><b>1 文件 = 1 组合件</b>；内容 = 实例（标识三元组 + 版本 + 配置 + 端口几何）+ 网络（成员 + 名称）+ 布局 + 活动面；</item>
///   <item><b>不含</b>：Runtime State 与绑定（运行时重建，§9.2）；</item>
///   <item><b>不自动执行任何代码</b>：加载只重建声明结构（§14 安全）；</item>
///   <item>本类型是**解析后的内存模型**；文本形态与未知字段保留见 <see cref="CompositeSerializer"/>。</item>
/// </list>
/// </remarks>
public sealed class Composite
{
    /// <summary>当前组合件 Schema 版本。</summary>
    public const int CurrentSchemaVersion = 1;

    /// <summary>Schema 版本（文件内嵌，加载时用于迁移判断）。</summary>
    public int SchemaVersion { get; set; } = CurrentSchemaVersion;

    /// <summary>组合件名（保存时由用户或文件名给定）。</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>保存时间（仅供人读与 trace；不参与任何判定）。</summary>
    public DateTimeOffset SavedAt { get; set; } = DateTimeOffset.Now;

    /// <summary>实例记录（**保存顺序 = 加入顺序**，用于加载后重算建网次序语义）。</summary>
    public IReadOnlyList<CompositeInstanceRecord> Instances { get; set; } = [];

    /// <summary>网络记录。</summary>
    public IReadOnlyList<CompositeNetworkRecord> Networks { get; set; } = [];

    /// <summary>布局记录（位置 / 尺寸 / 视图开关；**加载可忽略**）。</summary>
    public IReadOnlyList<ModuleLayoutView> Layout { get; set; } = [];

    /// <summary>
    /// 未知字段底稿（根层）：加载时保留原始根对象，保存时**只更新已知字段**——
    /// 未识别字段原样带回（C3-3 / AC-4 无损往返）。
    /// </summary>
    internal JsonObject? RootFragment { get; set; }

    /// <inheritdoc />
    public override string ToString() => $"{Name}（{Instances.Count} 实例 / {Networks.Count} 网络）";
}

/// <summary>
/// 组合件中的一条**实例记录**（§9.2 内容边界：实例 + 配置 + 活动面 + 端口几何）。
/// </summary>
public sealed class CompositeInstanceRecord
{
    /// <summary>实例 ID（工作现场内唯一、稳定；网络成员靠 <c>实例ID.口名</c> 重锚）。</summary>
    public string InstanceId { get; set; } = string.Empty;

    /// <summary>模块标识字面量（作者/模块名/版本——**含版本**，加载按版本重锚）。</summary>
    public string ModuleId { get; set; } = string.Empty;

    /// <summary>活动面：启用（true）/ 禁用（false）。</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// 配置片段：键 = 配置类型完整名，值 = 该配置的 JSON 对象。
    /// </summary>
    /// <remarks>
    /// 用"类型名 → 配置"的**统一形态**而非特例展平：单类型时略啰嗦，但**无信息损失、无多义**，
    /// 且天然支持同一模块的多个配置类型（模块自己决定 <c>Read&lt;T&gt;</c> 的类型）。
    /// </remarks>
    public JsonObject? Configuration { get; set; }

    /// <summary>端口几何（只记录**被用户调整过**的端口；未出现的端口用默认值）。</summary>
    public IReadOnlyList<PortGeometryView> Ports { get; set; } = [];

    /// <summary>实例记录片段的未知字段底稿（按实例 ID 与文件对应）。</summary>
    internal JsonObject? Fragment { get; set; }
}

/// <summary>
/// 组合件中的一条**网络记录**（§9.2 内容边界：成员 + 名称 + 匿名/命名 + 自动建网标记）。
/// </summary>
/// <remarks>匿名/命名由 <see cref="Name"/> 是否为空表达——与运行时模型同一事实源，不重复记录布尔量。</remarks>
public sealed class CompositeNetworkRecord
{
    /// <summary>网络名（空串 = 匿名直连）。</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>是否由快速建网（R0–R6）生成——**自动名与手动名不靠前缀猜测**。</summary>
    public bool IsAutoGenerated { get; set; }

    /// <summary>源成员（<c>实例ID.口名</c>）。</summary>
    public string Source { get; set; } = string.Empty;

    /// <summary>宿成员（<c>实例ID.口名</c>，1:N）。</summary>
    public IReadOnlyList<string> Targets { get; set; } = [];

    /// <summary>悬空成员（<c>实例ID.口名</c>）：上次加载时无法重锚的口——**声明保留**以便补齐后重锚。</summary>
    public IReadOnlyList<string> Unresolved { get; set; } = [];

    /// <summary>网络记录片段的未知字段底稿（按网络名与文件对应）。</summary>
    internal JsonObject? Fragment { get; set; }
}
